CREATE OR REPLACE FUNCTION pg_temp.expect_error(test_name TEXT, stmt TEXT)
RETURNS VOID AS $$
BEGIN
    EXECUTE stmt;
    RAISE NOTICE 'FAIL  %：沒有被擋下', test_name;
EXCEPTION WHEN OTHERS THEN
    RAISE NOTICE 'PASS  %：%', test_name, SQLERRM;
END;
$$ LANGUAGE plpgsql;

