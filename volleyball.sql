-- 猴子大學排球隊隊員與活動管理系統（多系隊版）
-- 01_schema.sql：建立資料表、限制、索引、觸發器與統計用 view
-- DBMS：PostgreSQL 14 以上
--
-- 注意：PostgreSQL 會把未加雙引號的識別字轉成小寫，
--       所以 tId 在資料庫中實際名稱為 tid，Flask 取回的欄位名稱也是小寫。
-- =====================================================================

