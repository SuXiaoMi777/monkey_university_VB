-- 重複執行時先清除舊資料表（依相依順序反向刪除）
DROP VIEW  IF EXISTS v_player_attendance;
DROP TABLE IF EXISTS Attendance CASCADE;
DROP TABLE IF EXISTS Account    CASCADE;
DROP TABLE IF EXISTS Event      CASCADE;
DROP TABLE IF EXISTS Player     CASCADE;
DROP TABLE IF EXISTS Venue      CASCADE;
DROP TABLE IF EXISTS Position   CASCADE;
DROP TABLE IF EXISTS Department CASCADE;
DROP TABLE IF EXISTS Team       CASCADE;

-- ---------------------------------------------------------------------
-- 1. 系所
-- ---------------------------------------------------------------------
CREATE TABLE Department (
    dId      VARCHAR(10)  PRIMARY KEY,
    college  VARCHAR(30)  NOT NULL,
    dName    VARCHAR(30)  NOT NULL UNIQUE
);

-- ---------------------------------------------------------------------
-- 2. 隊伍（系隊）
--    Own（Department 1:N Team，隊伍端完全參與）→ dId NOT NULL
--    每個系所最多一支男排、一支女排
-- ---------------------------------------------------------------------
CREATE TABLE Team (
    tId       SERIAL       PRIMARY KEY,
    teamName  VARCHAR(20)  NOT NULL UNIQUE,
    tGender   CHAR(1)      NOT NULL CHECK (tGender IN ('M', 'F')),
    dId       VARCHAR(10)  NOT NULL REFERENCES Department(dId) ON UPDATE CASCADE ON DELETE RESTRICT,
    CONSTRAINT uq_team_dept_gender UNIQUE (dId, tGender)
);

-- ---------------------------------------------------------------------
-- 3. 場上位置
-- ---------------------------------------------------------------------
CREATE TABLE Position (
    posId        VARCHAR(5)   PRIMARY KEY,
    posName      VARCHAR(10)  NOT NULL UNIQUE,
    description  TEXT
);

-- ---------------------------------------------------------------------
-- 4. 場地
-- ---------------------------------------------------------------------
CREATE TABLE Venue (
    vId       SERIAL       PRIMARY KEY,
    vName     VARCHAR(30)  NOT NULL UNIQUE,
    location  VARCHAR(50)
);

-- ---------------------------------------------------------------------
-- 5. 球員
--    Belong（Team 1:N Player，完全參與）→ tId NOT NULL
--    Enroll（Department 1:N Player，部分參與）→ dId 可為 NULL
--      這裡的 dId 是球員「就讀」的系所；隊伍所屬系所記錄在 Team.dId，
--      兩者通常相同，但允許雙主修、輔系等外系同學加入系隊。
--      系統管理員刪除某個系所時，其他系隊中就讀該系的同學 dId 改為 NULL（未填寫）
--    Play（Position 1:N Player，部分參與）→ posId 可為 NULL
-- ---------------------------------------------------------------------
CREATE TABLE Player (
    pId        VARCHAR(10)  PRIMARY KEY,
    pName      VARCHAR(20)  NOT NULL,
    gender     CHAR(1)      NOT NULL CHECK (gender IN ('M', 'F')),
    phone      VARCHAR(15),
    joinDate   DATE         NOT NULL DEFAULT CURRENT_DATE,
    jerseyNo   SMALLINT     CHECK (jerseyNo BETWEEN 0 AND 99),
    pStatus    VARCHAR(4)   NOT NULL DEFAULT '在隊'
                            CHECK (pStatus IN ('在隊', '退隊', '畢業')),
    leaveDate  DATE,
    tId        INT          NOT NULL REFERENCES Team(tId)       ON UPDATE CASCADE ON DELETE RESTRICT,
    dId        VARCHAR(10)           REFERENCES Department(dId) ON UPDATE CASCADE ON DELETE RESTRICT,
    posId      VARCHAR(5)            REFERENCES Position(posId) ON UPDATE CASCADE ON DELETE SET NULL,
    -- 在隊時不可有離隊日期；退隊或畢業時必須有離隊日期
    CONSTRAINT chk_player_leave CHECK (
        (pStatus = '在隊' AND leaveDate IS NULL) OR
        (pStatus <> '在隊' AND leaveDate IS NOT NULL AND leaveDate >= joinDate)
    )
);

-- 同一隊「在隊」球員的背號不可重複；已離隊學長姐的背號可以再被使用
CREATE UNIQUE INDEX uq_player_team_jersey
    ON Player (tId, jerseyNo)
    WHERE pStatus = '在隊';

-- ---------------------------------------------------------------------
-- 6. 活動場次
--    Hold（Team 1:N Event，完全參與）→ tId NOT NULL
--    Host（Venue 1:N Event，完全參與）→ vId NOT NULL
-- ---------------------------------------------------------------------
CREATE TABLE Event (
    eId        SERIAL       PRIMARY KEY,
    eventDate  DATE         NOT NULL,
    startTime  TIME         NOT NULL,
    endTime    TIME         NOT NULL,
    eventType  VARCHAR(6)   NOT NULL CHECK (eventType IN ('例行練球', '友誼賽')),
    semester   VARCHAR(5)   NOT NULL,              -- 例：115-1
    eStatus    VARCHAR(4)   NOT NULL DEFAULT '正常'
                            CHECK (eStatus IN ('正常', '已取消')),
    tId        INT          NOT NULL REFERENCES Team(tId)  ON UPDATE CASCADE ON DELETE RESTRICT,
    vId        INT          NOT NULL REFERENCES Venue(vId) ON UPDATE CASCADE ON DELETE RESTRICT,
    CONSTRAINT chk_event_time CHECK (endTime > startTime)
);

CREATE INDEX idx_event_venue_date ON Event (vId, eventDate);
CREATE INDEX idx_event_team_sem   ON Event (tId, semester);

-- ---------------------------------------------------------------------
-- 7. 出席紀錄（M:N 關係 Attend）
--    外鍵皆為 RESTRICT：已有出席紀錄的球員或活動不能被實際刪除，只能註銷
-- ---------------------------------------------------------------------
CREATE TABLE Attendance (
    pId      VARCHAR(10)  NOT NULL REFERENCES Player(pId) ON UPDATE CASCADE ON DELETE RESTRICT,
    eId      INT          NOT NULL REFERENCES Event(eId)  ON UPDATE CASCADE ON DELETE RESTRICT,
    aStatus  VARCHAR(2)   NOT NULL CHECK (aStatus IN ('出席', '遲到', '請假', '缺席')),
    note     VARCHAR(100),
    PRIMARY KEY (pId, eId)
);

-- ---------------------------------------------------------------------
-- 8. 帳號
--    三種角色：
--      admin   系統管理員：管理系所、隊伍、球經帳號、場地，查看全校統計
--      manager 系隊球經：只能管理自己系所的隊伍、球員、活動
--      player  球員：查看自己的出席、請假、修改個人資料
--    Bind  （Account 1:1 Player，雙方部分參與）→ pId 加 UNIQUE
--    Manage（Department 1:N Account，帳號端部分參與）→ dId 記錄球經負責的系所
-- ---------------------------------------------------------------------
CREATE TABLE Account (
    username      VARCHAR(20)   PRIMARY KEY,
    passwordHash  VARCHAR(255)  NOT NULL,
    role          VARCHAR(10)   NOT NULL CHECK (role IN ('admin', 'manager', 'player')),
    aName         VARCHAR(20),                       -- 顯示名稱（球經、管理員用）
    pId           VARCHAR(10)   UNIQUE REFERENCES Player(pId) ON UPDATE CASCADE ON DELETE CASCADE,
    dId           VARCHAR(10)   REFERENCES Department(dId) ON UPDATE CASCADE ON DELETE RESTRICT,
    -- 球員帳號只連結球員；球經帳號只連結系所；管理員兩者都不連結
    CONSTRAINT chk_account_role CHECK (
        (role = 'admin'   AND pId IS NULL     AND dId IS NULL) OR
        (role = 'manager' AND pId IS NULL     AND dId IS NOT NULL) OR
        (role = 'player'  AND pId IS NOT NULL AND dId IS NULL)
    )
);

-- =====================================================================
-- 觸發器
-- =====================================================================

-- (1) 同一場地、同一天、時段重疊的「正常」活動不可重複預約（對應 F2、F13）
CREATE OR REPLACE FUNCTION fn_check_venue_overlap() RETURNS TRIGGER AS $$
BEGIN
    IF NEW.eStatus = '正常' AND EXISTS (
        SELECT 1
        FROM Event e
        WHERE e.vId = NEW.vId
          AND e.eventDate = NEW.eventDate
          AND e.eStatus = '正常'
          AND e.eId <> NEW.eId
          AND e.startTime < NEW.endTime
          AND NEW.startTime < e.endTime
    ) THEN
        RAISE EXCEPTION '場地衝突：該場地在 % % 至 % 已有其他活動',
            NEW.eventDate, NEW.startTime, NEW.endTime;
    END IF;
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

CREATE TRIGGER trg_event_venue_overlap
    BEFORE INSERT OR UPDATE ON Event
    FOR EACH ROW EXECUTE FUNCTION fn_check_venue_overlap();

-- (2) 球員的性別必須和所屬隊伍的組別相符（男排只收男生、女排只收女生）
CREATE OR REPLACE FUNCTION fn_check_player_team_gender() RETURNS TRIGGER AS $$
BEGIN
    IF NEW.gender <> (SELECT tGender FROM Team WHERE tId = NEW.tId) THEN
        RAISE EXCEPTION '球員性別與隊伍組別不符';
    END IF;
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

CREATE TRIGGER trg_player_team_gender
    BEFORE INSERT OR UPDATE OF gender, tId ON Player
    FOR EACH ROW EXECUTE FUNCTION fn_check_player_team_gender();

-- (3) 出席紀錄的球員必須屬於該活動的隊伍
CREATE OR REPLACE FUNCTION fn_check_attendance_team() RETURNS TRIGGER AS $$
BEGIN
    IF (SELECT tId FROM Player WHERE pId = NEW.pId)
       <> (SELECT tId FROM Event WHERE eId = NEW.eId) THEN
        RAISE EXCEPTION '球員 % 不屬於活動 % 的隊伍', NEW.pId, NEW.eId;
    END IF;
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

CREATE TRIGGER trg_attendance_team
    BEFORE INSERT OR UPDATE ON Attendance
    FOR EACH ROW EXECUTE FUNCTION fn_check_attendance_team();

-- =====================================================================
-- 統計用 view：每位球員每學期的出席統計（F15、F16 共用）
--   應到次數 = 該學期「未取消」且「已舉行」活動中，該球員的紀錄筆數
--   實際出席 = 狀態為「出席」或「遲到」的筆數
-- =====================================================================
CREATE VIEW v_player_attendance AS
SELECT
    p.pId,
    p.pName,
    p.tId,
    t.teamName,
    t.dId           AS team_dId,   -- 隊伍所屬系所，用來限制球經只能看自己系所
    p.pStatus,
    e.semester,
    COUNT(*)                                                AS expected_cnt,
    COUNT(*) FILTER (WHERE a.aStatus IN ('出席', '遲到'))   AS attended_cnt,
    COUNT(*) FILTER (WHERE a.aStatus = '遲到')              AS late_cnt,
    COUNT(*) FILTER (WHERE a.aStatus = '請假')              AS leave_cnt,
    COUNT(*) FILTER (WHERE a.aStatus = '缺席')              AS absent_cnt,
    ROUND(100.0 * COUNT(*) FILTER (WHERE a.aStatus IN ('出席', '遲到'))
          / NULLIF(COUNT(*), 0), 1)                         AS attendance_rate
FROM Attendance a
JOIN Event  e ON e.eId = a.eId
JOIN Player p ON p.pId = a.pId
JOIN Team   t ON t.tId = p.tId
WHERE e.eStatus = '正常'
  AND e.eventDate <= CURRENT_DATE
GROUP BY p.pId, p.pName, p.tId, t.teamName, t.dId, p.pStatus, e.semester;

